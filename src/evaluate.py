LABELS = list(range(C.NUM_CLASSES))
SHORT = [n.replace("[Malignant] ", "") for n in C.CLASS_NAMES]
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def _clean(v):
    return None if isinstance(v, float) and math.isnan(v) else v


def metrics_for(y, p):
    pred = p.argmax(1)
    out = {"accuracy": float(accuracy_score(y, pred))}
    for avg in ("macro", "weighted"):
        pr, rc, f1, _ = precision_recall_fscore_support(y, pred, average=avg, labels=LABELS, zero_division=0)
        out.update({f"{avg}_precision": float(pr), f"{avg}_recall": float(rc), f"{avg}_f1": float(f1)})
    out["kappa"] = _clean(float(cohen_kappa_score(y, pred, labels=LABELS)))
    try:
        out["roc_auc_ovr"] = float(roc_auc_score(y, p, multi_class="ovr", labels=LABELS))
    except ValueError:  # a class missing from y
        out["roc_auc_ovr"] = None
    rep = classification_report(y, pred, labels=LABELS, target_names=C.CLASS_NAMES, output_dict=True, zero_division=0)
    out["per_class"] = {c: {k: float(rep[c][k]) for k in ("precision", "recall", "f1-score", "support")}
                        for c in C.CLASS_NAMES}
    out["confusion_matrix"] = confusion_matrix(y, pred, labels=LABELS).tolist()
    return out


def comparison_table(metrics, best=None):
    rows = ["| Model | Accuracy | Macro-F1 | Weighted-F1 | Kappa | ROC-AUC (OvR) |", "|---|---|---|---|---|---|"]
    fmt = lambda v: "–" if v is None else f"{v:.4f}"  # noqa: E731
    for k, m in metrics["models"].items():
        name = C.DISPLAY_NAMES[k]
        name = f"**{name}** (selected)" if k == best else name
        rows.append(f"| {name} | {fmt(m['accuracy'])} | {fmt(m['macro_f1'])} | {fmt(m['weighted_f1'])} | "
                    f"{fmt(m['kappa'])} | {fmt(m['roc_auc_ovr'])} |")
    meta = metrics["meta"]
    note = (f"\n_Test split: {meta['n_test']} images, data source: **{meta['source']}**"
            f"{' (SMOKE run, numbers meaningless)' if meta['smoke'] else ''}. "
            f"Generated by `src/evaluate.py` at {meta['generated_at']}._")
    return "\n".join(rows) + "\n" + note + "\n"


def write_readme_table(metrics=None, readme=None):
    metrics = metrics or json.loads(C.METRICS_JSON.read_text())
    readme = readme or C.README_PATH
    text = readme.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise ValueError(f"{readme} has no {START} / {END} markers")
    head, rest = text.split(START, 1)
    tail = rest.split(END, 1)[1]
    readme.write_text(f"{head}{START}\n{comparison_table(metrics, metrics['best_ensemble'])}{END}{tail}", encoding="utf-8")


def notes(metrics):
    """Plain statement of which ENDGOAL targets are met."""
    best = metrics["models"][metrics["best_ensemble"]]
    backbones = {k: v for k, v in metrics["models"].items() if k in C.BACKBONES}
    top = max(backbones, key=lambda k: backbones[k]["accuracy"])
    margin = 100 * (best["accuracy"] - backbones[top]["accuracy"])
    min_recall = min(v["recall"] for v in best["per_class"].values())
    checks = [
        (f"Ensemble accuracy ≥ {C.TARGET_ACCURACY:.0%}", f"{best['accuracy']:.4f}", best["accuracy"] >= C.TARGET_ACCURACY),
        (f"Ensemble macro-F1 ≥ {C.TARGET_MACRO_F1}", f"{best['macro_f1']:.4f}", best["macro_f1"] >= C.TARGET_MACRO_F1),
        (f"Beats best backbone ({C.DISPLAY_NAMES[top]}) by ≥ {C.TARGET_MARGIN_PP} pp", f"{margin:+.2f} pp",
         margin >= C.TARGET_MARGIN_PP),
        (f"Every class recall ≥ {C.TARGET_CLASS_RECALL}", f"min {min_recall:.4f}", min_recall >= C.TARGET_CLASS_RECALL),
    ]
    meta = metrics["meta"]
    lines = [f"# Target check: {C.DISPLAY_NAMES[metrics['best_ensemble']]}", "",
             f"Data source: **{meta['source']}**{' (SMOKE)' if meta['smoke'] else ''}, {meta['n_test']} test images.", "",
             "| Target | Value | Met |", "|---|---|---|"]
    lines += [f"| {t} | {v} | {'yes' if ok else 'NO'} |" for t, v, ok in checks]
    if margin < C.TARGET_MARGIN_PP:
        lines += ["", "The ensemble does not beat the best single backbone by the target margin. "
                  "Next things to try (ENDGOAL.md): kappa-weighted voting, test-time augmentation, swapping a backbone."]
    return "\n".join(lines) + "\n"


# ---------- figures ----------

def _save(fig, name):
    C.FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    fig.savefig(C.FIGURES_DIR / name, dpi=120, bbox_inches="tight")
    plt.close(fig)


def plot_confusion(key, cm):
    fig, ax = plt.subplots(figsize=(5, 4.2))
    sns.heatmap(np.array(cm), annot=True, fmt="d", cmap="Blues", xticklabels=SHORT, yticklabels=SHORT, ax=ax, cbar=False)
    ax.set(xlabel="Predicted", ylabel="True", title=C.DISPLAY_NAMES[key])
    _save(fig, f"cm_{key}.png")


def plot_training_curves(name):
    f = C.HISTORY_DIR / f"{name}.csv"
    if not f.is_file():
        return
    h = pd.read_csv(f)
    fig, axes = plt.subplots(1, 2, figsize=(9, 3.5))
    for ax, metric in zip(axes, ("loss", "accuracy")):
        ax.plot(h["epoch"] + 1, h[metric], marker="o", label="train")
        if f"val_{metric}" in h:
            ax.plot(h["epoch"] + 1, h[f"val_{metric}"], marker="o", label="val")
        ax.set(xlabel="epoch", title=metric)
        ax.legend()
    fig.suptitle(C.DISPLAY_NAMES[name])
    _save(fig, f"training_curves_{name}.png")


def plot_roc(key, y, p):
    fig, ax = plt.subplots(figsize=(5, 4.5))
    for i, c in enumerate(SHORT):
        if (y == i).any() and (y != i).any():
            fpr, tpr, _ = roc_curve(y == i, p[:, i])
            ax.plot(fpr, tpr, label=c)
    ax.plot([0, 1], [0, 1], "k--", lw=0.8)
    ax.set(xlabel="False positive rate", ylabel="True positive rate", title=f"One-vs-rest ROC: {C.DISPLAY_NAMES[key]}")
    ax.legend(loc="lower right")
    _save(fig, "roc_ensemble.png")


def plot_comparison(metrics):
    keys = list(metrics["models"])
    x = np.arange(len(keys))
    fig, ax = plt.subplots(figsize=(8, 4))
    for off, metric in ((-0.2, "accuracy"), (0.2, "macro_f1")):
        ax.bar(x + off, [metrics["models"][k][metric] for k in keys], 0.4, label=metric)
    ax.set_xticks(x, [C.DISPLAY_NAMES[k] for k in keys], rotation=20)
    ax.set(ylim=(0, 1.05), title="Test-set comparison")
    ax.legend()
    _save(fig, "model_comparison_bar.png")


def plot_gradcam_grid(test, y, pred, models, weights):
    """Row 0: a correctly classified example per class; row 1: a misclassified one."""
    from src.gradcam import gradcam_overlay
    name = max(models, key=lambda n: weights.get(n, 0))
    m, s = models[name], img_size(models[name])
    fig, axes = plt.subplots(2, C.NUM_CLASSES, figsize=(3 * C.NUM_CLASSES, 6.4))
    for row, want_correct in enumerate((True, False)):
        for i in range(C.NUM_CLASSES):
            ax = axes[row, i]
            ax.axis("off")
            idx = np.where((y == i) & ((pred == y) == want_correct))[0]
            if not len(idx):
                ax.text(0.5, 0.5, "none", ha="center", va="center")
            else:
                j = idx[0]
                raw = load_image_array(resolve(test["path"].iloc[j]), s)
                ax.imshow(gradcam_overlay(m, name, preprocess_fn(name)(raw[None].copy()), raw, int(pred[j])))
            ax.set_title(f"{'correct' if want_correct else 'wrong'} | true {SHORT[i]}"
                         + (f"\npred {SHORT[pred[idx[0]]]}" if len(idx) else ""), fontsize=9)
    fig.suptitle(f"Grad-CAM ({C.DISPLAY_NAMES[name]}, highest ensemble weight)")
    _save(fig, "gradcam_examples.png")


# ---------- main ----------

def run(progress_cb=None, write_readme=False):
    test_csv = C.SPLITS_DIR / "test.csv"
    if not test_csv.is_file():
        raise FileNotFoundError("No test split. Make the splits first.")
    test = pd.read_csv(C.SPLITS_DIR / "test.csv")
    y = test["label_idx"].values
    models = load_models()
    voting, stacking = load_voting(), load_stacking()
    if not models:
        raise FileNotFoundError("No trained backbones in models/. Train them first.")
    if not (voting and stacking):
        raise FileNotFoundError("Ensemble not fitted. Run the ensemble stage first.")

    probs = predict_probs(models, test)
    probs["voting"] = voting_probs(probs, voting["weights"])
    if all(n in probs for n in stacking["models"]):
        probs["stacking"] = stacking_probs(stacking, probs)
    if progress_cb:
        progress_cb("evaluate", 1, {"msg": "test predictions done"})

    per_model = {k: metrics_for(y, p) for k, p in probs.items()}
    ens = [k for k in C.ENSEMBLES if k in per_model]
    best = max(ens, key=lambda k: (per_model[k]["macro_f1"], k == "voting"))  # tie -> voting
    meta = split_meta() or {}
    metrics = {
        "meta": {"source": meta.get("source"), "smoke": bool(meta.get("smoke")), "n_test": int(len(y)),
                 "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
                 "voting_weights": voting["weights"]},
        "models": per_model,
        "best_ensemble": best,
    }
    C.RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    C.METRICS_JSON.write_text(json.dumps(metrics, indent=2))
    C.MODE_FILE.write_text(best)
    (C.RESULTS_DIR / "comparison_table.md").write_text(comparison_table(metrics, best), encoding="utf-8")
    (C.RESULTS_DIR / "NOTES.md").write_text(notes(metrics), encoding="utf-8")

    for k, m in per_model.items():
        plot_confusion(k, m["confusion_matrix"])
    for n in C.BACKBONES:
        plot_training_curves(n)
    plot_roc(best, y, probs[best])
    plot_comparison(metrics)
    plot_gradcam_grid(test, y, probs[best].argmax(1), models, voting["weights"])
    if progress_cb:
        progress_cb("evaluate", 2, {"best_ensemble": best, "macro_f1": per_model[best]["macro_f1"]})
    if write_readme:
        write_readme_table(metrics)
    return metrics


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--write-readme-table", action="store_true")
    ap.add_argument("--table-only", action="store_true", help="inject from existing metrics.json, no test pass")
    a = ap.parse_args()
    if a.table_only:
        write_readme_table()
    else:
        run(write_readme=a.write_readme_table)
    print((C.RESULTS_DIR / "comparison_table.md").read_text(encoding="utf-8"))
