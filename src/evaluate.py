def run(progress_cb=None, write_readme=False):
    test_csv = C.SPLITS_DIR / "test.csv"
    if not test_csv.is_file():
        raise FileNotFoundError("No test split. Make the splits first.")
    test = pd.read_csv(C.SPLITS_DIR / "test.csv")
    y = test["label_idx"].values
    models = load_models()
    voting, stacking = load_voting(), load_stacking()
    if not models:
        raise FileNotFoundError("No trained backbones in models/. Train them first.")
    if not (voting and stacking):
        raise FileNotFoundError("Ensemble not fitted. Run the ensemble stage first.")

    probs = predict_probs(models, test)
    probs["voting"] = voting_probs(probs, voting["weights"])
    if all(n in probs for n in stacking["models"]):
        probs["stacking"] = stacking_probs(stacking, probs)
    if progress_cb:
        progress_cb("evaluate", 1, {"msg": "test predictions done"})

    per_model = {k: metrics_for(y, p) for k, p in probs.items()}
    ens = [k for k in C.ENSEMBLES if k in per_model]
    best = max(ens, key=lambda k: (per_model[k]["macro_f1"], k == "voting"))  # tie -> voting
    meta = split_meta() or {}
    metrics = {
        "meta": {"source": meta.get("source"), "smoke": bool(meta.get("smoke")), "n_test": int(len(y)),
                 "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
                 "voting_weights": voting["weights"]},
        "models": per_model,
        "best_ensemble": best,
    }
    C.RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    C.MODE_FILE.write_text(best)  # before MC: the uncertainty run combines with the SELECTED head

    smoke = bool(meta.get("smoke"))
    unc = uncertainty_section(test, y, progress_cb=progress_cb, T=C.MC_PASSES_SMOKE if smoke else None)
    if unc:
        metrics["uncertainty"] = unc
        if unc["errors_flagged_pct"] is not None and unc["correct_flagged_pct"] is not None:
            auroc = unc["entropy_auroc_vs_wrong"]
            print(f"flagged {unc['errors_flagged_pct']}% of errors at a cost of "
                  f"{unc['correct_flagged_pct']}% of correct predictions "
                  f"(T={unc['passes']}" + (f", entropy AUROC {auroc}" if auroc is not None else "") + ")",
                  flush=True)

    C.METRICS_JSON.write_text(json.dumps(metrics, indent=2))
    (C.RESULTS_DIR / "comparison_table.md").write_text(
        comparison_table(metrics, best) + uncertainty_table(metrics), encoding="utf-8")
    (C.RESULTS_DIR / "NOTES.md").write_text(notes(metrics), encoding="utf-8")
    (C.RESULTS_DIR / "run_info.json").write_text(json.dumps(run_info(metrics, voting), indent=2))
    np.savez(C.RESULTS_DIR / "test_probs.npz", y=y, **{n: probs[n] for n in C.BACKBONES})
    ood.write_stats([resolve(p) for p in load_split("train")["path"]])  # models/ood_stats.json for upload checks

    top = max(C.BACKBONES, key=lambda k: per_model[k]["accuracy"])
    margin_pp = 100 * (per_model[best]["accuracy"] - per_model[top]["accuracy"])
    if not metrics["meta"]["smoke"] and margin_pp < C.TARGET_MARGIN_PP:
        section = fallback_attempts(per_model, {n: probs[n] for n in C.BACKBONES}, y)
        if section:
            with (C.RESULTS_DIR / "NOTES.md").open("a", encoding="utf-8") as f:
                f.write(section)

    for k, m in per_model.items():
        plot_confusion(k, m["confusion_matrix"])
    for n in C.BACKBONES:
        plot_training_curves(n)
    plot_roc(best, y, probs[best])
    plot_comparison(metrics)
    plot_gradcam_grid(test, y, probs[best].argmax(1), models, voting["weights"])
    if progress_cb:
        progress_cb("evaluate", 2, {"best_ensemble": best, "macro_f1": per_model[best]["macro_f1"]})
    if write_readme:
        write_readme_table(metrics)
    return metrics


