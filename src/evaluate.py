def _clean(v):
    return None if isinstance(v, float) and math.isnan(v) else v


def metrics_for(y, p):
    pred = p.argmax(1)
    out = {"accuracy": float(accuracy_score(y, pred))}
    for avg in ("macro", "weighted"):
        pr, rc, f1, _ = precision_recall_fscore_support(y, pred, average=avg, labels=LABELS, zero_division=0)
        out.update({f"{avg}_precision": float(pr), f"{avg}_recall": float(rc), f"{avg}_f1": float(f1)})
    out["kappa"] = _clean(float(cohen_kappa_score(y, pred, labels=LABELS)))
    try:
        out["roc_auc_ovr"] = float(roc_auc_score(y, p, multi_class="ovr", labels=LABELS))
    except ValueError:  # a class missing from y
        out["roc_auc_ovr"] = None
    rep = classification_report(y, pred, labels=LABELS, target_names=C.CLASS_NAMES, output_dict=True, zero_division=0)
    out["per_class"] = {c: {k: float(rep[c][k]) for k in ("precision", "recall", "f1-score", "support")}
                        for c in C.CLASS_NAMES}
    out["confusion_matrix"] = confusion_matrix(y, pred, labels=LABELS).tolist()
    return out


def comparison_table(metrics, best=None):
    rows = ["| Model | Accuracy | Macro-F1 | Weighted-F1 | Kappa | ROC-AUC (OvR) |", "|---|---|---|---|---|---|"]
    fmt = lambda v: "–" if v is None else f"{v:.4f}"  # noqa: E731
    for k, m in metrics["models"].items():
        name = C.DISPLAY_NAMES[k]
        name = f"**{name}** (selected)" if k == best else name
        rows.append(f"| {name} | {fmt(m['accuracy'])} | {fmt(m['macro_f1'])} | {fmt(m['weighted_f1'])} | "
                    f"{fmt(m['kappa'])} | {fmt(m['roc_auc_ovr'])} |")
    meta = metrics["meta"]
    note = (f"\n_Test split: {meta['n_test']} images, data source: **{meta['source']}**"
            f"{' (SMOKE run, numbers meaningless)' if meta['smoke'] else ''}. "
            f"Generated by `src/evaluate.py` at {meta['generated_at']}._")
    return "\n".join(rows) + "\n" + note + "\n"


def uncertainty_table(metrics):
    """'Uncertainty' sub-table for comparison_table.md. Empty string when MC has not been run."""
    u = metrics.get("uncertainty")
    if not u:
        return ""
    f = lambda v, s="": "–" if v is None else f"{v}{s}"  # noqa: E731
    t = u["thresholds"]
    rows = [
        "", "### Uncertainty (MC Dropout)", "",
        "| Measure | Value |", "|---|---|",
        f"| Stochastic passes (T) | {u['passes']} |",
        f"| Review threshold (entropy ≥) | {t['review']:.4f} |",
        f"| Low-confidence threshold (entropy ≥) | {t['low_confidence']:.4f} |",
        f"| Errors flagged | {f(u['errors_flagged_pct'], '%')} |",
        f"| Correct predictions flagged | {f(u['correct_flagged_pct'], '%')} |",
        f"| Mean entropy, correct | {f(u['mean_entropy_correct'])} |",
        f"| Mean entropy, wrong | {f(u['mean_entropy_wrong'])} |",
        f"| Entropy AUROC as wrong-prediction detector | {f(u['entropy_auroc_vs_wrong'])} |",
        f"| Mutual-information AUROC | {f(u['mi_auroc_vs_wrong'])} |",
        f"| Flags (HIGH / MEDIUM / LOW) | {u['flag_counts']['HIGH']} / "
        f"{u['flag_counts']['MEDIUM']} / {u['flag_counts']['LOW']} |",
        "",
        f"_Thresholds calibrated on the **{t['calibrated_on']}** split ({t['method']} method); "
        f"the numbers above are measured on test._",
    ]
    if u.get("caveat"):
        rows += ["", f"> **Note:** {u['caveat']}"]
    return "\n".join(rows) + "\n"


def write_readme_table(metrics=None, readme=None):
    metrics = metrics or json.loads(C.METRICS_JSON.read_text())
    readme = readme or C.README_PATH
    text = readme.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise ValueError(f"{readme} has no {START} / {END} markers")
    head, rest = text.split(START, 1)
    tail = rest.split(END, 1)[1]
    readme.write_text(f"{head}{START}\n{comparison_table(metrics, metrics['best_ensemble'])}{END}{tail}", encoding="utf-8")


